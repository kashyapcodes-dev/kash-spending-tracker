/** `public`: no session. `authenticated`: any signed-in user. Otherwise the minimum budget role. */
export type Access = "public" | "authenticated" | Role;

export interface EndpointDef {
  /** Stable identifier, used as the OpenAPI operationId and as the client method name. */
  id: string;
  method: "get" | "post" | "patch" | "put" | "delete";
  /** OpenAPI-style path, for example `/api/v1/budgets/{budgetId}`. */
  path: string;
  summary: string;
  access: Access;
  /** Why a public endpoint is safe, or what an authenticated one returns. */
  authzNote: string;
  params?: z.ZodObject;
  query?: z.ZodObject;
  body?: z.ZodType;
  bodyKind?: "json" | "multipart";
  success: { status: number; schema: z.ZodType };
  /** Name of the child-ID path parameter, if any (drives M1-AZ-5). */
  childParam?:
    | "categoryId"
    | "transactionId"
    | "userId"
    | "inviteId"
    | "dashboardId"
    | "conversationId"
    | "proposalId"
    | "tokenId"
    | "presetId"
    | "stagedId"
    | "batchId"
    | "connectionId";
  /** True if the body can reference another budget's resource (drives M1-AZ-6). */
  foreignRef?: boolean;
}

